// Generate packages/sdk: the type definitions and Tailwind tokens view
// plugins build against. Run with `just sdk`.
import { execFileSync } from "node:child_process"
import { mkdir, readFile, rm, writeFile } from "node:fs/promises"
import { join } from "node:path"

import { SHARED_MODULE_IDS } from "../src/views/shared-modules.ts"

const root = new URL("..", import.meta.url).pathname
const work = join(root, "target/sdk")
const out = join(root, "packages/sdk")
const bin = (name) => join(root, "node_modules/.bin", name)
const header = (comment) => `${comment} Generated by \`just sdk\`. Do not edit.\n`

// tsc resolves the host's path aliases and ambient types; the bundler then
// inlines everything except the modules the host shares with plugins.
await rm(work, { recursive: true, force: true })
execFileSync(bin("tsc"), ["-p", "tsconfig.sdk.json", "--outDir", join(work, "dts")], {
  cwd: root,
  stdio: "inherit",
})
await writeFile(
  join(work, "tsconfig.json"),
  JSON.stringify({
    compilerOptions: {
      module: "ESNext",
      moduleResolution: "bundler",
      jsx: "react-jsx",
      strict: true,
      skipLibCheck: true,
      baseUrl: ".",
      paths: { "@/*": ["./dts/*"] },
    },
    files: ["dts/sdk/index.d.ts"],
  }),
)
const types = join(work, "index.d.ts")
execFileSync(
  bin("dts-bundle-generator"),
  [
    "--project",
    join(work, "tsconfig.json"),
    "--no-check",
    "--no-banner",
    "--silent",
    "--export-referenced-types=false",
    "--external-inlines",
    "class-variance-authority",
    "clsx",
    "-o",
    types,
    join(work, "dts/sdk/index.d.ts"),
  ],
  { cwd: root, stdio: "inherit" },
)

// The @theme, @custom-variant and @utility rules of global.css. Theme blocks
// become references: the host already defines their variables.
function tailwindTokens(css) {
  const blocks = []
  for (const match of css.matchAll(/^@(theme|custom-variant|utility)\b[^\n]*/gm)) {
    let end = match.index + match[0].length
    if (match[0].endsWith("{")) {
      let depth = 1
      while (depth > 0) {
        const char = css[end++]
        if (char === "{") depth++
        else if (char === "}") depth--
      }
    }
    blocks.push(css.slice(match.index, end).replace(/^@theme( inline)? \{/, "@theme$1 reference {"))
  }
  return blocks.join("\n\n")
}

await mkdir(out, { recursive: true })
await writeFile(join(out, "index.d.ts"), header("//") + (await readFile(types, "utf8")))
// Plugin builds mark these external, so the list can't drift from the host's.
await writeFile(
  join(out, "shared-modules.js"),
  header("//") +
    "// Modules renCal provides to view plugins at runtime; leave them out of the bundle.\n" +
    `export const sharedModules = ${JSON.stringify(SHARED_MODULE_IDS, null, 2)}\n`,
)
await writeFile(
  join(out, "shared-modules.d.ts"),
  header("//") + "export declare const sharedModules: readonly string[]\n",
)
await writeFile(
  join(out, "theme.css"),
  header("/*").replace("\n", " */\n") +
    tailwindTokens(await readFile(join(root, "src/global.css"), "utf8")) +
    "\n",
)
